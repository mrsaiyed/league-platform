// T-76, by hand: the fields each read of the role matrix gives each kind of person
// (P4 §4, R-16), as paths (`players[].firstName`; `[]` is an empty list, `*` a map's
// id). `all` is what everyone who may use the read is given; a `guarded` field is
// given only to whoever holds its permission (who holds what is the matrix's own
// table, written from the spec); `byActor` replaces `all` for one kind of person.
//
// Written out here, never read from core. Every read runs with a person who has
// every private field R-16 names on the roster of the team it is about, so a read
// that hands out one more field, to anyone, makes the matrix fail until the field is
// written here, with the permission that covers it if it is private.
import type { Permission } from '@srleagues/core';

