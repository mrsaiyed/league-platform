// Writes supabase/setup.sql: everything a new Supabase project needs for live stats,
// in one file to paste into its SQL editor. The tables (001-schema.sql), the API the
// static site calls (002-api.sql) and the 2026–27 TCSAAL schedule. Safe to run again:
// nothing is dropped, tracked games are never changed and the schedule is only
// updated for games nobody has tracked. Run `npm run build:supabase` after changing
// any of those; a test checks the file is up to date.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { DEFAULT_RULES, newGame } from '../packages/sports/src/basketball/live.ts';
import { SCHEMA_FILES } from '../packages/database/src/live-stats/postgres.ts';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const seed = JSON.parse(
  fs.readFileSync(
    path.join(root, 'apps/live-stats/data/tcsaal-alhadi-varsity-boys-2026-27.json'),
    'utf8',
  ),
);
const lit = (v) =>
  v === null || v === undefined ? 'NULL' : `'${String(v).replaceAll("'", "''")}'`;

export function setupSql() {
  const schema = SCHEMA_FILES.map((file) =>
    fs.readFileSync(path.join(root, 'packages/database/src/live-stats', file), 'utf8').trim(),
  );
  const teams = [
    { ...seed.team, tracked: true },
    ...seed.opponents.map((o) => ({ ...o, sourceUrl: '', tracked: false })),
  ];
  const state = JSON.stringify(newGame(DEFAULT_RULES, 0));
  const games = seed.games.map(
    (g) =>
      `  (${[
        seed.season,
        g.home,
        g.away,
        new Date(g.startsAt).toISOString(),
        g.venue,
        g.address,
        g.type,
        seed.source,
        `${seed.source.toLowerCase()}:${g.number}`,
        g.sourceUrl,
      ]
        .map(lit)
        .join(', ')})`,
  );
  return `-- Live stats for Supabase: paste this whole file into the SQL editor and Run.
-- Generated by scripts/build-supabase-sql.mjs from packages/database/src/live-stats
-- and the season's fixtures; do not edit by hand. Safe to run again.
--
-- Afterwards, set the scorer passcode (not kept in any file):
--   select live_stats.set_scorer_passcode('choose a passcode of 12+ characters');

-- ==== Tables (001-schema.sql) =========================================================
${schema[0]}

-- ==== The static site's API (002-api.sql) =============================================
${schema[1]}

-- ==== The ${seed.season} schedule, from ${seed.source} ===================================
INSERT INTO live_stats.teams(id, slug, name, school, tracked, source_url) VALUES
${teams.map((t) => `  (gen_random_uuid(), ${[t.slug, t.name, t.school].map(lit).join(', ')}, ${t.tracked}, ${lit(t.sourceUrl)})`).join(',\n')}
ON CONFLICT (slug) DO NOTHING;

INSERT INTO live_stats.games(id, season, home_team_id, away_team_id, starts_at, venue,
  venue_address, game_type, source, source_ref, source_url, state)
SELECT gen_random_uuid(), f.season, h.id, a.id, f.starts_at::timestamptz, f.venue, f.address,
  f.game_type, f.source, f.source_ref, f.source_url, ${lit(state)}::jsonb
FROM (VALUES
${games.join(',\n')}
) AS f(season, home, away, starts_at, venue, address, game_type, source, source_ref, source_url)
JOIN live_stats.teams h ON h.slug = f.home
JOIN live_stats.teams a ON a.slug = f.away
ON CONFLICT (source_ref) DO UPDATE SET starts_at = excluded.starts_at, venue = excluded.venue,
  venue_address = excluded.venue_address, game_type = excluded.game_type,
  source_url = excluded.source_url, home_team_id = excluded.home_team_id,
  away_team_id = excluded.away_team_id
WHERE live_stats.games.status = 'scheduled' AND live_stats.games.revision = 0;

-- Tell Supabase's API about the new functions straight away.
NOTIFY pgrst, 'reload schema';
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  fs.mkdirSync(path.join(root, 'supabase'), { recursive: true });
  fs.writeFileSync(path.join(root, 'supabase/setup.sql'), setupSql());
  console.log('Wrote supabase/setup.sql.');
}
